-- tmux prefix and repeat mode
rex.bind("`>`", "pane.send_key", { key = "`" })
rex.bind("`>shift+7", "client.tab.close")
rex.bind("`>x", "pane.close")
rex.bind("`>h", "pane.focus", { direction = "left" })
rex.bind("`>j", "pane.focus", { direction = "down" })
rex.bind("`>k", "pane.focus", { direction = "up" })
rex.bind("`>l", "pane.focus", { direction = "right" })
rex.bind("`>shift+'", "pane.split", { direction = "down" })
rex.bind("`>shift+5", "pane.split", { direction = "right" })
rex.bind("`>;", "pane.split", { direction = "up" })

rex.mode("repeat", { exclusive = true })
rex.bind("`>r", "client.mode.enter", { name = "repeat" })
rex.bind("repeat/enter", "client.mode.exit")
rex.bind("repeat/escape", "client.mode.exit")
rex.bind("repeat/h", "pane.focus", { direction = "left" })
rex.bind("repeat/j", "pane.focus", { direction = "down" })
rex.bind("repeat/k", "pane.focus", { direction = "up" })
rex.bind("repeat/l", "pane.focus", { direction = "right" })

-- Ghostty-style shortcuts.
rex.bind("cmd+k", "com.superlogical.terminal.clear")
rex.bind("alt+cmd+k", "session.switch")
rex.bind("f1", "pane.zoom")
rex.bind("cmd+enter", "pane.split", { direction = "right" })
rex.bind("shift+cmd+enter", "pane.split", { direction = "down" })
rex.bind("shift+cmd+w", "pane.close")
rex.bind("ctrl+alt+l", "client.tab.next")
rex.bind("ctrl+alt+h", "client.tab.previous")
rex.bind("shift+cmd+h", "pane.focus", { direction = "left" })
rex.bind("shift+cmd+l", "pane.focus", { direction = "right" })
rex.bind("shift+cmd+k", "pane.focus", { direction = "up" })
rex.bind("shift+cmd+j", "pane.focus", { direction = "down" })

rex.bind("ctrl+shift+left", "pane.resize", { direction = "left" })
rex.bind("ctrl+shift+right", "pane.resize", { direction = "right" })
rex.bind("ctrl+shift+up", "pane.resize", { direction = "up" })
rex.bind("ctrl+shift+down", "pane.resize", { direction = "down" })

